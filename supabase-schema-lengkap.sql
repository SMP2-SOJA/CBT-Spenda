-- Peserta, guru, admin
create table if not exists users (
    id         bigint generated by default as identity primary key,
    name       text not null,
    username   text not null unique,
    password   text not null,
    role       text not null default 'siswa',
    kelas      text,
    mapel      text,
    created_at timestamptz default now()
);

-- Jadwal ujian (PIN, durasi, acak, token, lokasi)
create table if not exists schedules (
    id           bigint generated by default as identity primary key,
    mapel        text not null,
    tanggal      text,
    durasi       int  default 60,
    pin          text,
    status       text default 'Aktif',
    acak_soal    boolean default false,
    acak_opsi    boolean default false,
    wajib_token  boolean default false,
    wajib_lokasi boolean default false,
    created_at   timestamptz default now()
);

-- Bank soal
create table if not exists questions (
    id         bigint generated by default as identity primary key,
    exam_id    text not null,
    tipe       text not null default 'PG',
    tanya      text,
    opsi_json  text,
    kunci      text,
    media_path text,
    skor       numeric default 1,
    gform_url  text,
    created_at timestamptz default now()
);
create index if not exists questions_exam_idx on questions (exam_id);

-- Nilai akhir
create table if not exists results (
    id             bigint generated by default as identity primary key,
    student_name   text not null,
    mapel          text not null,
    nilai          text,
    benar          int default 0,
    salah          int default 0,
    detail_jawaban text,
    tanggal        text,
    kelas          text,
    created_at     timestamptz default now()
);
create index if not exists results_mapel_idx on results (mapel);

-- Pemantauan langsung (status, progres)
create table if not exists activity (
    id           bigint generated by default as identity primary key,
    student_name text not null,
    exam_name    text not null,
    status       text,
    score        text,
    last_seen    text,
    kelas        text,
    created_at   timestamptz default now()
);
create unique index if not exists activity_student_exam_uniq on activity (student_name, exam_name);

-- Profil sekolah, logo, pengaturan
create table if not exists config (
    key   text primary key,
    value text
);

-- Anti joki: kunci perangkat per siswa per ujian
create table if not exists exam_sessions (
    id             bigint generated by default as identity primary key,
    student_name   text not null,
    username       text,
    kelas          text,
    mapel          text not null,
    device_id      text,
    device_info    text,
    ip             text,
    lokasi         text,
    percobaan      int  default 0,
    percobaan_info text,
    created_at     timestamptz default now(),
    updated_at     timestamptz default now(),
    unique (student_name, mapel)
);

-- Gambar soal
create table if not exists media (
    id         text primary key,
    mime       text not null,
    data       text not null,
    size       int,
    uploader   text,
    created_at timestamptz default now()
);

-- Kunci akses: hanya server (secret key) yang boleh membaca/menulis
alter table users         enable row level security;
alter table schedules     enable row level security;
alter table questions     enable row level security;
alter table results       enable row level security;
alter table activity      enable row level security;
alter table config        enable row level security;
alter table exam_sessions enable row level security;
alter table media         enable row level security;
grant all on all tables    in schema public to service_role;
grant all on all sequences in schema public to service_role;

-- Setelah memulihkan cadangan: lanjutkan nomor id dari data terakhir
create or replace function cbt_reset_sequences() returns void
language plpgsql security definer set search_path = public as $$
declare t text;
begin
    foreach t in array array['users','schedules','questions','results','activity','exam_sessions'] loop
        execute format(
            'select setval(pg_get_serial_sequence(%L, ''id''), greatest(coalesce((select max(id) from %I), 0), 1), (select count(*) > 0 from %I))',
            t, t, t);
    end loop;
end $$;
revoke all on function cbt_reset_sequences() from public, anon, authenticated;
grant execute on function cbt_reset_sequences() to service_role;

